"""Tests for deterministic model-card generation (``core/model_cards.py``).

Model cards are generated by pure code from on-disk artifacts
(findings.json, progress.json, urika.toml) — no agent involved. The
core contract: every section is filled ONLY with data that actually
exists on disk; anything missing renders as "Not recorded for this
run." — the generator never invents content.

The assumptions/caveats section draws on two on-disk sources: the
per-experiment latest evaluation at
``experiments/<exp>/labbook/evaluation.json`` (the orchestrator loop
persists each parseable ``parse_evaluation`` result there, including
``assessment.method_validity.assumptions_detail``) rendered first with
an explicit per-experiment-latest provenance line, then findings.json
``limitations``. Missing/corrupt evaluation.json falls back to
limitations alone — pinned here.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from urika.core.model_cards import generate_model_cards

_FINDINGS = {
    "question": "Does X predict Y?",
    "answer": "Yes — X predicts Y with R²=0.41 in a ridge model.",
    "final_methods": [
        {
            "name": "ridge",
            "role": "primary_prediction",
            "script": "methods/final_ridge.py",
            "run_id": "run-001",
            "experiment_id": "exp-001-baseline",
            "key_metrics": {"r2": 0.41},
            "summary": "Ridge regression predicts Y from X with R²=0.41.",
        }
    ],
    "limitations": [
        "Small sample (n=40).",
        "Residual normality was not formally tested.",
    ],
}

_RUN = {
    "run_id": "run-001",
    "method": "ridge",
    "params": {"alpha": 1.0},
    "metrics": {"r2": 0.41, "rmse": 0.15},
    "metrics_with_uncertainty": {
        "r2": {
            "value": 0.41,
            "ci_lower": 0.33,
            "ci_upper": 0.49,
            "confidence": 0.95,
        }
    },
}


@pytest.fixture
def project_dir(tmp_path: Path) -> Path:
    proj = tmp_path / "proj"
    proj.mkdir()
    (proj / "urika.toml").write_text(
        "[project]\n"
        'name = "proj"\n'
        'question = "Does X predict Y?"\n'
        'mode = "exploratory"\n'
        'description = ""\n'
        'data_paths = ["data/x.csv"]\n'
        "\n[preferences]\n"
        'audience = "standard"\n',
        encoding="utf-8",
    )
    exp = proj / "experiments" / "exp-001-baseline"
    exp.mkdir(parents=True)
    (exp / "progress.json").write_text(
        json.dumps({"runs": [_RUN], "status": "completed"}), encoding="utf-8"
    )
    (proj / "projectbook").mkdir()
    (proj / "projectbook" / "findings.json").write_text(
        json.dumps(_FINDINGS), encoding="utf-8"
    )
    (proj / "methods").mkdir()
    (proj / "methods" / "final_ridge.py").write_text(
        "import numpy as np\n", encoding="utf-8"
    )
    return proj


class TestGenerateModelCards:
    def test_writes_one_card_per_final_method(self, project_dir: Path) -> None:
        paths = generate_model_cards(project_dir)
        assert paths == [project_dir / "methods" / "ridge_model_card.md"]
        assert paths[0].exists()

    def test_card_carries_method_identity(self, project_dir: Path) -> None:
        (path,) = generate_model_cards(project_dir)
        body = path.read_text(encoding="utf-8")
        assert "ridge" in body
        assert "methods/final_ridge.py" in body
        assert "primary_prediction" in body
        assert "Ridge regression predicts Y from X" in body

    def test_card_carries_intended_use_from_toml(self, project_dir: Path) -> None:
        (path,) = generate_model_cards(project_dir)
        body = path.read_text(encoding="utf-8")
        assert "Does X predict Y?" in body
        assert "exploratory" in body

    def test_card_carries_data_paths(self, project_dir: Path) -> None:
        (path,) = generate_model_cards(project_dir)
        assert "data/x.csv" in path.read_text(encoding="utf-8")

    def test_metrics_come_from_matched_run_record_with_ci(
        self, project_dir: Path
    ) -> None:
        (path,) = generate_model_cards(project_dir)
        body = path.read_text(encoding="utf-8")
        # Full run-record metrics (not just findings key_metrics) + CI.
        assert "r2=0.41" in body
        assert "rmse=0.15" in body
        assert "[95% CI 0.33–0.49]" in body
        # Provenance back to the exact run.
        assert "run-001" in body
        assert "exp-001-baseline" in body

    def test_metrics_fall_back_to_key_metrics_when_run_missing(
        self, project_dir: Path
    ) -> None:
        findings = dict(_FINDINGS)
        findings["final_methods"] = [
            {**_FINDINGS["final_methods"][0], "run_id": "run-999"}
        ]
        (project_dir / "projectbook" / "findings.json").write_text(
            json.dumps(findings), encoding="utf-8"
        )
        (path,) = generate_model_cards(project_dir)
        body = path.read_text(encoding="utf-8")
        assert "r2=0.41" in body
        assert "rmse=0.15" not in body  # run record was not matched

    def test_run_record_found_via_disk_labbook(self, project_dir: Path) -> None:
        """Runs recorded only as labbook/run-*.json (not in
        progress.json) are still matched — same tolerance as
        ``read_disk_run_records``."""
        exp = project_dir / "experiments" / "exp-001-baseline"
        (exp / "progress.json").write_text(
            json.dumps({"runs": [], "status": "completed"}), encoding="utf-8"
        )
        labbook = exp / "labbook"
        labbook.mkdir()
        (labbook / "run-001-record.json").write_text(json.dumps(_RUN), encoding="utf-8")
        (path,) = generate_model_cards(project_dir)
        body = path.read_text(encoding="utf-8")
        assert "rmse=0.15" in body
        assert "[95% CI 0.33–0.49]" in body

    def test_limitations_fill_assumptions_section(self, project_dir: Path) -> None:
        (path,) = generate_model_cards(project_dir)
        body = path.read_text(encoding="utf-8")
        assert "Small sample (n=40)." in body
        assert "Residual normality was not formally tested." in body

    def test_missing_sections_render_not_recorded(self, tmp_path: Path) -> None:
        """A bare project (no toml details, no runs, no limitations)
        still gets a card per final method — with every empty section
        reading "Not recorded for this run." and nothing invented."""
        proj = tmp_path / "bare"
        (proj / "projectbook").mkdir(parents=True)
        (proj / "projectbook" / "findings.json").write_text(
            json.dumps({"final_methods": [{"name": "mystery"}]}),
            encoding="utf-8",
        )
        (path,) = generate_model_cards(proj)
        body = path.read_text(encoding="utf-8")
        assert "Not recorded for this run." in body
        # No fabricated metrics, data, or caveats.
        assert "r2" not in body
        assert "data/" not in body

    def test_no_findings_returns_empty(self, tmp_path: Path) -> None:
        proj = tmp_path / "empty"
        proj.mkdir()
        assert generate_model_cards(proj) == []

    def test_malformed_findings_returns_empty(self, tmp_path: Path) -> None:
        proj = tmp_path / "bad"
        (proj / "projectbook").mkdir(parents=True)
        (proj / "projectbook" / "findings.json").write_text(
            "{not json", encoding="utf-8"
        )
        assert generate_model_cards(proj) == []

    def test_empty_final_methods_returns_empty(self, tmp_path: Path) -> None:
        proj = tmp_path / "none"
        (proj / "projectbook").mkdir(parents=True)
        (proj / "projectbook" / "findings.json").write_text(
            json.dumps({"final_methods": []}), encoding="utf-8"
        )
        assert generate_model_cards(proj) == []

    def test_novice_audience_adds_glossary_explainer(self, project_dir: Path) -> None:
        from urika.core.method_glossary import explain_method

        (path,) = generate_model_cards(project_dir, audience="novice")
        explainer = explain_method("ridge")
        assert explainer is not None
        assert explainer in path.read_text(encoding="utf-8")

    def test_standard_audience_omits_glossary_explainer(
        self, project_dir: Path
    ) -> None:
        from urika.core.method_glossary import explain_method

        (path,) = generate_model_cards(project_dir, audience="standard")
        explainer = explain_method("ridge")
        assert explainer is not None
        assert explainer not in path.read_text(encoding="utf-8")

    def test_rewrites_are_versioned(self, project_dir: Path) -> None:
        generate_model_cards(project_dir)
        generate_model_cards(project_dir)
        versions = list((project_dir / "methods").glob("ridge_model_card-*.md"))
        assert versions, "second write must preserve the first as a dated version"

    def test_method_name_is_slugified_for_filename(self, project_dir: Path) -> None:
        findings = dict(_FINDINGS)
        findings["final_methods"] = [
            {**_FINDINGS["final_methods"][0], "name": "ridge / tuned α"}
        ]
        (project_dir / "projectbook" / "findings.json").write_text(
            json.dumps(findings), encoding="utf-8"
        )
        (path,) = generate_model_cards(project_dir)
        assert path.parent == project_dir / "methods"
        assert "/" not in path.name and " " not in path.name

    def test_entries_without_name_are_skipped(self, project_dir: Path) -> None:
        findings = dict(_FINDINGS)
        findings["final_methods"] = [
            "not-a-dict",
            {"role": "robustness"},
            _FINDINGS["final_methods"][0],
        ]
        (project_dir / "projectbook" / "findings.json").write_text(
            json.dumps(findings), encoding="utf-8"
        )
        paths = generate_model_cards(project_dir)
        assert paths == [project_dir / "methods" / "ridge_model_card.md"]


_EVALUATION = {
    "turn": 3,
    "experiment_id": "exp-001-baseline",
    "evaluation": {
        "criteria_met": False,
        "assessment": {
            "method_validity": {
                "appropriate_test": True,
                "assumptions_checked": False,
                "assumptions_detail": [
                    {
                        "name": "normality of residuals",
                        "test": "not checked",
                        "result": "unknown",
                        "implication": "reported p-values may be unreliable",
                    },
                    {
                        "name": "homoscedasticity",
                        "test": "Breusch-Pagan",
                        "result": "passed (p=0.41)",
                        "implication": "no correction needed",
                    },
                ],
            }
        },
    },
}

_PROVENANCE_LINE = (
    "From the latest evaluation of experiment exp-001-baseline "
    "(may post-date this specific run):"
)


class TestAssumptionsFromEvaluation:
    """The assumptions section consumes the persisted per-experiment
    latest evaluation (``labbook/evaluation.json``) when present —
    rendered above findings.json limitations with an explicit
    per-experiment-latest provenance line (never claimed per-run)."""

    def _labbook(self, project_dir: Path) -> Path:
        labbook = project_dir / "experiments" / "exp-001-baseline" / "labbook"
        labbook.mkdir(exist_ok=True)
        return labbook

    def test_assumptions_detail_rendered_with_provenance(
        self, project_dir: Path
    ) -> None:
        (self._labbook(project_dir) / "evaluation.json").write_text(
            json.dumps(_EVALUATION), encoding="utf-8"
        )
        (path,) = generate_model_cards(project_dir)
        body = path.read_text(encoding="utf-8")
        assert _PROVENANCE_LINE in body
        # Each entry renders name/test/result/implication.
        assert "normality of residuals" in body
        assert "not checked" in body
        assert "reported p-values may be unreliable" in body
        assert "homoscedasticity" in body
        assert "Breusch-Pagan" in body
        assert "passed (p=0.41)" in body
        # findings.json limitations still render, BELOW the detail.
        assert "Small sample (n=40)." in body
        assert body.index("normality of residuals") < body.index("Small sample (n=40).")

    def test_corrupt_evaluation_falls_back_to_limitations(
        self, project_dir: Path
    ) -> None:
        (self._labbook(project_dir) / "evaluation.json").write_text(
            "{not json", encoding="utf-8"
        )
        (path,) = generate_model_cards(project_dir)
        body = path.read_text(encoding="utf-8")
        assert "Small sample (n=40)." in body
        assert "From the latest evaluation" not in body

    def test_missing_evaluation_keeps_current_fallback(self, project_dir: Path) -> None:
        (path,) = generate_model_cards(project_dir)
        body = path.read_text(encoding="utf-8")
        assert "Small sample (n=40)." in body
        assert "From the latest evaluation" not in body

    def test_evaluation_without_assumptions_detail_is_ignored(
        self, project_dir: Path
    ) -> None:
        (self._labbook(project_dir) / "evaluation.json").write_text(
            json.dumps({"turn": 1, "evaluation": {"criteria_met": True}}),
            encoding="utf-8",
        )
        (path,) = generate_model_cards(project_dir)
        body = path.read_text(encoding="utf-8")
        assert "Small sample (n=40)." in body
        assert "From the latest evaluation" not in body
