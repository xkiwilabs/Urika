"""Jupyter reproduce notebook — ``projectbook/reproduce.ipynb``.

``urika finalize`` calls :func:`write_reproduce_notebook` (pure code,
no agent) to assemble a runnable notebook from artifacts the finalizer
already wrote: findings.json names the final methods and their
standalone scripts under ``methods/``; each script's LITERAL file
contents become one code cell. The generator never invents code — a
missing script degrades to a markdown note without a code cell.

Structure: title md cell (research question + answer), setup code cell
(commented ``%pip install -r requirements.txt`` + sys.path note), one
md cell (name, key metrics incl. confidence intervals from the matched
run record, summary) + one code cell per final method, closing md cell
pointing at METRICS.md and the model cards.

The notebook is validated with ``nbformat.validate`` before writing and
written through :func:`urika.core.report_writer.write_versioned`
(.ipynb is JSON text, so the versioned text writer applies).
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

from urika.core.labbook import _format_ci
from urika.core.model_cards import _find_run_record, _load_findings
from urika.core.report_writer import write_versioned

logger = logging.getLogger(__name__)

_SETUP_SOURCE = """\
# Uncomment to install the project's dependencies into this kernel:
# %pip install -r requirements.txt

# Run this notebook from the project root (the directory containing
# urika.toml) so the relative data paths inside the method scripts
# resolve; the sys.path entry makes project-local helper modules
# importable.
import sys

sys.path.insert(0, ".")"""

_CLOSING_SOURCE = """\
---

**Further reading:** [`METRICS.md`](METRICS.md) explains every metric
used in this project in plain language; the per-method model cards in
[`../methods/`](../methods/) document intended use, training data,
metrics, and known limitations for each finalized method."""


def write_reproduce_notebook(project_dir: Path) -> Path | None:
    """Write ``projectbook/reproduce.ipynb`` from findings.json.

    Returns the written path, or ``None`` (with a log warning) when
    findings.json is missing/malformed or names no final methods.
    """
    findings = _load_findings(project_dir)
    if findings is None:
        logger.warning(
            "Reproduce notebook: no readable findings.json in %s — skipping",
            project_dir / "projectbook",
        )
        return None
    methods = findings.get("final_methods")
    if not isinstance(methods, list) or not methods:
        logger.warning(
            "Reproduce notebook: findings.json names no final methods — skipping"
        )
        return None

    import nbformat

    cells = [
        nbformat.v4.new_markdown_cell(_title_source(findings)),
        nbformat.v4.new_code_cell(_SETUP_SOURCE),
    ]
    for entry in methods:
        if not isinstance(entry, dict):
            continue
        name = str(entry.get("name") or "").strip()
        if not name:
            continue
        cells.append(
            nbformat.v4.new_markdown_cell(_method_md_source(project_dir, entry))
        )
        script_source = _script_source(project_dir, entry)
        if script_source is not None:
            cells.append(nbformat.v4.new_code_cell(script_source))
    cells.append(nbformat.v4.new_markdown_cell(_CLOSING_SOURCE))

    nb = nbformat.v4.new_notebook(cells=cells)
    nb.metadata["kernelspec"] = {
        "name": "python3",
        "display_name": "Python 3",
        "language": "python",
    }
    nb.metadata["language_info"] = {"name": "python"}
    nbformat.validate(nb)

    path = project_dir / "projectbook" / "reproduce.ipynb"
    path.parent.mkdir(parents=True, exist_ok=True)
    return write_versioned(path, nbformat.writes(nb) + "\n")


def _title_source(findings: dict[str, Any]) -> str:
    question = str(findings.get("question") or "").strip()
    answer = str(findings.get("answer") or "").strip()
    lines = [f"# Reproduce — {question}" if question else "# Reproduce"]
    if answer:
        lines += ["", f"**Answer:** {answer}"]
    lines += [
        "",
        "Generated by `urika finalize`. Each section below embeds the",
        "standalone script for one finalized method, verbatim.",
    ]
    return "\n".join(lines)


def _method_md_source(project_dir: Path, entry: dict[str, Any]) -> str:
    name = str(entry.get("name"))
    lines = [f"## {name}"]
    summary = str(entry.get("summary") or "").strip()
    if summary:
        lines += ["", summary]

    metric_parts = _metric_parts(project_dir, entry)
    if metric_parts:
        lines += ["", f"**Key metrics:** {', '.join(metric_parts)}"]

    script = str(entry.get("script") or "").strip()
    script_missing = not script or not (project_dir / script).exists()
    if script_missing:
        label = f"`{script}`" if script else "for this method"
        lines += [
            "",
            f"*Script {label} was not found on disk — the code cell was "
            "omitted (this notebook never invents code).*",
        ]
    return "\n".join(lines)


def _metric_parts(project_dir: Path, entry: dict[str, Any]) -> list[str]:
    """``key_metrics`` rendered ``name=value [CI]`` — the CI comes from
    the run record named by run_id/experiment_id, when one exists."""
    key_metrics = entry.get("key_metrics")
    if not isinstance(key_metrics, dict) or not key_metrics:
        return []
    run = _find_run_record(
        project_dir,
        str(entry.get("experiment_id") or ""),
        str(entry.get("run_id") or ""),
    )
    uncertainty: dict[str, Any] = {}
    if run is not None and isinstance(run.get("metrics_with_uncertainty"), dict):
        uncertainty = run["metrics_with_uncertainty"]
    parts = []
    for key, value in key_metrics.items():
        part = f"{key}={value}"
        ci_entry = uncertainty.get(key)
        ci = _format_ci(ci_entry) if isinstance(ci_entry, dict) else ""
        if ci:
            part = f"{part} {ci}"
        parts.append(part)
    return parts


def _script_source(project_dir: Path, entry: dict[str, Any]) -> str | None:
    """The LITERAL script file contents, or None when absent/unreadable."""
    script = str(entry.get("script") or "").strip()
    if not script:
        return None
    path = project_dir / script
    if not path.exists():
        return None
    try:
        return path.read_text(encoding="utf-8")
    except OSError as exc:
        logger.warning("Reproduce notebook: cannot read %s: %s", path, exc)
        return None
