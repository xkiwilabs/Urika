"""Deterministic model cards for finalized methods.

``urika finalize`` produces ``projectbook/findings.json`` naming the
final methods with run-id traceability. This module turns each
``final_methods[]`` entry into a ``methods/<name>_model_card.md`` —
an adaptation of the Hugging Face model-card template filled ONLY
with data that actually exists on disk:

- method identity (name, role, script, summary) from findings.json;
- intended use (research question + mode) from urika.toml;
- training data (``data_paths``) from urika.toml — the builder's
  rows/columns profile is not persisted, so it is never quoted here;
- metrics (with confidence intervals) from the run record named by
  ``run_id``/``experiment_id``, via progress.json or the on-disk
  labbook/artifacts records (:func:`read_disk_run_records`);
- assumptions/caveats/limitations from findings.json ``limitations``
  (the evaluator's ``assumptions_detail`` is parsed in-memory only and
  never persisted, so findings.json is the sole on-disk source).

Anything missing renders as "Not recorded for this run." — the
generator NEVER invents content. Generated by pure code (no agent, no
API cost) so it is fully deterministic and unit-testable.
"""

from __future__ import annotations

import json
import logging
import re
from pathlib import Path
from typing import Any

from urika.core.labbook import _format_ci
from urika.core.method_glossary import explain_method
from urika.core.progress import load_progress
from urika.core.report_writer import write_versioned

logger = logging.getLogger(__name__)

NOT_RECORDED = "Not recorded for this run."


def generate_model_cards(project_dir: Path, audience: str = "standard") -> list[Path]:
    """Write one versioned model card per findings.json final method.

    Returns the written paths (empty when findings.json is missing,
    malformed, or names no final methods). ``audience="novice"`` adds
    the method-glossary one-line explainer where one exists. Never
    raises on missing/partial project artifacts — every absent section
    renders as :data:`NOT_RECORDED`.
    """
    findings = _load_findings(project_dir)
    if findings is None:
        return []
    methods = findings.get("final_methods")
    if not isinstance(methods, list):
        return []

    question, mode, data_paths = _load_project_facts(project_dir)
    limitations = [
        str(item) for item in findings.get("limitations") or [] if str(item).strip()
    ]

    written: list[Path] = []
    for entry in methods:
        if not isinstance(entry, dict):
            continue
        name = str(entry.get("name") or "").strip()
        if not name:
            continue
        card = _render_card(
            project_dir,
            entry,
            question=question,
            mode=mode,
            data_paths=data_paths,
            limitations=limitations,
            audience=audience,
        )
        path = project_dir / "methods" / f"{_slugify(name)}_model_card.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        write_versioned(path, card)
        written.append(path)
    return written


def _load_findings(project_dir: Path) -> dict[str, Any] | None:
    path = project_dir / "projectbook" / "findings.json"
    if not path.exists():
        return None
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        logger.warning("Model cards: cannot read %s: %s", path, exc)
        return None
    return data if isinstance(data, dict) else None


def _load_project_facts(project_dir: Path) -> tuple[str, str, list[str]]:
    """(question, mode, data_paths) from urika.toml — "" / [] when absent."""
    toml_path = project_dir / "urika.toml"
    if not toml_path.exists():
        return "", "", []
    try:
        import tomllib

        with open(toml_path, "rb") as f:
            data = tomllib.load(f)
    except Exception as exc:
        logger.warning("Model cards: cannot read %s: %s", toml_path, exc)
        return "", "", []
    project = data.get("project", {}) if isinstance(data, dict) else {}
    question = str(project.get("question") or "")
    mode = str(project.get("mode") or "")
    raw_paths = project.get("data_paths")
    data_paths = [str(p) for p in raw_paths] if isinstance(raw_paths, list) else []
    return question, mode, data_paths


def _slugify(name: str) -> str:
    slug = re.sub(r"[^\w.-]+", "_", name.strip()).strip("_")
    return slug or "method"


def _find_run_record(
    project_dir: Path, experiment_id: str, run_id: str
) -> dict[str, Any] | None:
    """The run record named by findings.json, as a plain dict.

    progress.json is the canonical store; the labbook/artifacts
    ``run-*.json`` scan (:func:`read_disk_run_records`) is the same
    tolerance the orchestrator applies. Searches the named experiment
    first, then all experiments (findings written by cheaper models
    occasionally misname the experiment while the run_id is right).
    """
    if not run_id:
        return None
    experiments_dir = project_dir / "experiments"
    candidates: list[str] = []
    if experiment_id and (experiments_dir / experiment_id).is_dir():
        candidates.append(experiment_id)
    if experiments_dir.is_dir():
        for exp_dir in sorted(experiments_dir.iterdir()):
            if exp_dir.is_dir() and exp_dir.name not in candidates:
                candidates.append(exp_dir.name)

    for exp_id in candidates:
        for run in load_progress(project_dir, exp_id).get("runs", []):
            if isinstance(run, dict) and run.get("run_id") == run_id:
                run = dict(run)
                run["_experiment_id"] = exp_id
                return run
        try:
            from urika.orchestrator.parsing import read_disk_run_records

            for record in read_disk_run_records(experiments_dir / exp_id):
                if record.run_id == run_id:
                    run = record.to_dict()
                    run["_experiment_id"] = exp_id
                    return run
        except Exception as exc:
            logger.warning(
                "Model cards: disk run-record scan failed for %s: %s", exp_id, exc
            )
    return None


def _render_card(
    project_dir: Path,
    entry: dict[str, Any],
    *,
    question: str,
    mode: str,
    data_paths: list[str],
    limitations: list[str],
    audience: str,
) -> str:
    name = str(entry.get("name"))
    lines: list[str] = [f"# Model Card — {name}", ""]

    # --- Method ---
    lines.append("## Method")
    lines.append("")
    lines.append(f"- **Name:** {name}")
    role = str(entry.get("role") or "").strip()
    if role:
        lines.append(f"- **Role:** {role}")
    script = str(entry.get("script") or "").strip()
    if script:
        lines.append(f"- **Script:** `{script}`")
    summary = str(entry.get("summary") or "").strip()
    if summary:
        lines.append(f"- **Summary:** {summary}")
    if audience == "novice":
        explainer = explain_method(name)
        if explainer:
            lines.append("")
            lines.append(f"*What this method does:* {explainer}")
    lines.append("")

    # --- Intended use ---
    lines.append("## Intended Use")
    lines.append("")
    if question or mode:
        if question:
            lines.append(f"- **Research question:** {question}")
        if mode:
            lines.append(f"- **Project mode:** {mode}")
    else:
        lines.append(NOT_RECORDED)
    lines.append("")

    # --- Training data ---
    lines.append("## Training Data")
    lines.append("")
    if data_paths:
        lines.extend(f"- `{p}`" for p in data_paths)
    else:
        lines.append(NOT_RECORDED)
    lines.append("")

    # --- Metrics ---
    lines.append("## Metrics")
    lines.append("")
    lines.extend(_metrics_lines(project_dir, entry))
    lines.append("")

    # --- Assumptions / caveats / limitations ---
    # The evaluator's per-run ``assumptions_detail`` is not persisted
    # to disk, so the project-level findings.json ``limitations`` list
    # is the only honest on-disk source for this section.
    lines.append("## Assumptions, Caveats, and Limitations")
    lines.append("")
    if limitations:
        lines.extend(f"- {item}" for item in limitations)
    else:
        lines.append(NOT_RECORDED)
    lines.append("")

    return "\n".join(lines)


def _metrics_lines(project_dir: Path, entry: dict[str, Any]) -> list[str]:
    run_id = str(entry.get("run_id") or "")
    experiment_id = str(entry.get("experiment_id") or "")
    run = _find_run_record(project_dir, experiment_id, run_id)

    if run is not None:
        metrics = run.get("metrics") if isinstance(run.get("metrics"), dict) else {}
        uncertainty = run.get("metrics_with_uncertainty")
        if not isinstance(uncertainty, dict):
            uncertainty = {}
        if metrics:
            lines = []
            for key, value in metrics.items():
                part = f"- {key}={value}"
                ci_entry = uncertainty.get(key)
                ci = _format_ci(ci_entry) if isinstance(ci_entry, dict) else ""
                if ci:
                    part = f"{part} {ci}"
                lines.append(part)
            exp_id = run.get("_experiment_id") or experiment_id
            lines.append("")
            lines.append(f"Source: {run_id} (experiment {exp_id}).")
            return lines

    key_metrics = entry.get("key_metrics")
    if isinstance(key_metrics, dict) and key_metrics:
        lines = [f"- {key}={value}" for key, value in key_metrics.items()]
        lines.append("")
        lines.append(
            "Source: findings.json key_metrics (the underlying run record "
            "was not found on disk)."
        )
        return lines

    return [NOT_RECORDED]
